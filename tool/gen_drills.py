# Writes lib/lessons/drills.dart from drills_data.py.  python3 tool/gen_drills.py
import os
from dartgen import ds
from drills_data import DRILLS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'lib', 'lessons', 'drills.dart')

HEADER = """// GENERATED by tool/gen_drills.py from tool/drills_data.py. Do not edit by hand.
import '../engine/drill.dart';
import '../engine/piece.dart';

const List<Drill> drills = [
"""


def main():
    out = [HEADER]
    for d in DRILLS:
        out.append('  Drill(\n')
        out.append(f"    id: {ds(d['id'])},\n")
        out.append(f"    phase: {ds(d['phase'])},\n")
        out.append(f"    title: {ds(d['title'])},\n")
        out.append(f"    task: {ds(d['task'])},\n")
        out.append(f"    fen: {ds(d['fen'])},\n")
        out.append(f"    side: {d['side']},\n")
        out.append(f"    goal: DrillGoal.{d['goal']},\n")
        out.append(f"    maxMoves: {d['max']},\n")
        out.append(f"    hint: {ds(d['hint'])},\n")
        out.append(f"    level: {ds(d.get('level', 'expert'))},\n")
        if 'lesson' in d:
            out.append(f"    lesson: {ds(d['lesson'])},\n")
        out.append('  ),\n')
    out.append('];\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = ''.join(out).replace("side: white,", "side: white,")
    text = text.replace("side: black,", "side: black,")
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {len(DRILLS)} drills to lib/lessons/drills.dart')


if __name__ == '__main__':
    main()
