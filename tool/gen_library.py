# Writes lib/puzzles/library.dart from library.json.  python3 tool/gen_library.py
import json
import os
from dartgen import ds, dlist

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'lib', 'puzzles', 'library.dart')

HEADER = """// GENERATED by tool/curate.py + tool/gen_library.py. Do not edit by hand.
import '../engine/insight.dart';
import '../engine/puzzle.dart';

const List<Puzzle> puzzleLibrary = [
"""


def main():
    with open(os.path.join(HERE, 'library.json')) as f:
        lib = json.load(f)
    out = [HEADER]
    for e in lib:
        idea = f"Idea.{e['idea']}" if e['idea'] else 'null'
        out.append('  Puzzle(\n')
        out.append(f"    id: {ds(e['id'])},\n")
        out.append(f"    fen: {ds(e['fen'])},\n")
        out.append(f"    solutions: {dlist(e['solutions'])},\n")
        out.append(f"    san: {ds(e['san'])},\n")
        out.append(f"    idea: {idea},\n")
        out.append(f"    mateIn: {e['mate_in']},\n")
        out.append(f"    tier: {e['tier']},\n")
        out.append(f"    text: {ds(e['text'])},\n")
        out.append(f"    source: {ds(e['source'])},\n")
        out.append('  ),\n')
    out.append('];\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(''.join(out))
    print(f'wrote {len(lib)} puzzles to lib/puzzles/library.dart')


if __name__ == '__main__':
    main()
