# Writes lib/lessons/lessons.dart from lessons_data.py.  python3 tool/gen_lessons.py
import os
from dartgen import ds, dlist
from lessons_data import LESSONS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'lib', 'lessons', 'lessons.dart')

HEADER = """// GENERATED by tool/gen_lessons.py from tool/lessons_data.py. Do not edit by hand.
import '../engine/insight.dart';

/// What a lesson's example shows.
enum LessonKind {
  /// The piece on [Lesson.square] can go to exactly [Lesson.targets].
  moves,

  /// The position is check, checkmate or stalemate for the side to move.
  status,

  /// Playing [Lesson.move] shows [Lesson.idea].
  idea,

  /// Playing [Lesson.move] is the key move of an endgame or a plan; the lesson
  /// explains it in [Lesson.note].
  plan,

  /// An opening line: [Lesson.line] with a note per move, studied from the
  /// side [Lesson.side].
  line,

  /// A middlegame idea (pawn structure, files, outposts): [Lesson.targets] are
  /// the squares that show [Lesson.concept] for [Lesson.side] in [Lesson.fen].
  concept,
}

class Lesson {
  final String id;

  /// Curriculum level, see PLAN.md.
  final int level;
  final LessonKind kind;
  final String title;
  final String tagline;
  final String why;
  final List<String> spot;
  final String fen;

  final Idea? idea;
  final String? move;
  final String? square;
  final List<String> targets;

  /// 'check', 'checkmate' or 'stalemate' for [LessonKind.status].
  final String? status;

  /// What the key move achieves, for [LessonKind.plan].
  final String? note;

  /// Id of a training drill that practises the lesson.
  final String? drill;

  /// The moves of an opening line in SAN, and one note per move (may be empty).
  final List<String> line;
  final List<String> notes;

  /// 'white' or 'black': the side you study and are tested on.
  final String? side;

  /// Opening lines: other full lines (SAN, space separated) that branch off the
  /// main [line], with a name each in [branchNames].
  final List<String> branches;
  final List<String> branchNames;

  /// For famous games: the move (ply index) where the combination starts, so
  /// the trainer can begin from that position.
  final int? start;

  /// Name of the structure concept for [LessonKind.concept].
  final String? concept;

  const Lesson({
    required this.id,
    required this.level,
    required this.kind,
    required this.title,
    required this.tagline,
    required this.why,
    required this.spot,
    required this.fen,
    this.idea,
    this.move,
    this.square,
    this.targets = const [],
    this.status,
    this.note,
    this.drill,
    this.line = const [],
    this.notes = const [],
    this.side,
    this.start,
    this.branches = const [],
    this.branchNames = const [],
    this.concept,
  });
}

const List<Lesson> lessons = [
"""


def main():
    out = [HEADER]
    for l in LESSONS:
        out.append('  Lesson(\n')
        out.append(f"    id: {ds(l['id'])},\n")
        out.append(f"    level: {l['level']},\n")
        out.append(f"    kind: LessonKind.{l['kind']},\n")
        out.append(f"    title: {ds(l['title'])},\n")
        out.append(f"    tagline: {ds(l['tagline'])},\n")
        out.append(f"    why: {ds(l['why'])},\n")
        out.append(f"    spot: {dlist(l['spot'])},\n")
        out.append(f"    fen: {ds(l['fen'])},\n")
        if 'idea' in l:
            out.append(f"    idea: Idea.{l['idea']},\n")
        if 'move' in l:
            out.append(f"    move: {ds(l['move'])},\n")
        if 'square' in l:
            out.append(f"    square: {ds(l['square'])},\n")
        if 'targets' in l:
            out.append(f"    targets: {dlist(l['targets'])},\n")
        if 'status' in l:
            out.append(f"    status: {ds(l['status'])},\n")
        if 'note' in l:
            out.append(f"    note: {ds(l['note'])},\n")
        if 'drill' in l:
            out.append(f"    drill: {ds(l['drill'])},\n")
        if 'concept' in l:
            out.append(f"    concept: {ds(l['concept'])},\n")
            out.append(f"    side: {ds(l['side'])},\n")
        if 'line' in l:
            out.append(f"    line: {dlist(l['line'])},\n")
            out.append(f"    notes: {dlist(l['notes'])},\n")
            if 'start' in l:
                out.append(f"    start: {l['start']},\n")
            if l.get('branches'):
                out.append(f"    branches: {dlist(l['branches'])},\n")
                out.append(f"    branchNames: {dlist(l['branch_names'])},\n")
            out.append(f"    side: {ds(l['side'])},\n")
        out.append('  ),\n')
    out.append('];\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(''.join(out))
    print(f'wrote {len(LESSONS)} lessons to lib/lessons/lessons.dart')


if __name__ == '__main__':
    main()
